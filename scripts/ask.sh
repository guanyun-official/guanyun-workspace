#!/usr/bin/env bash
# ask.sh — **架构自问**(zoom-out:每一块在全景图里站在哪)。
#
# 它**不判断,只提问**。判断是模型的事,提问是机制的事。
# 机械检查器(regex/AST)永远查不出「这段代码在全景图里站错了位置」——那只有模型能回答。
# 而派子 agent 全量审太贵。所以只保留**最轻的那一层**:收口前把全景图摆在眼前,逐层对位。
#
# 死规矩:每条给 file:line 的真证据。**答不出证据 = 没看。**
set -u
cat <<'Q'

════════════════════════════════════════════════════════════════════════════
  架构自问 —— **这一轮碰过的每一块,在全景图里站在哪?**
  (不是查 bug,是对位。全景图见 docs/架构.md)
════════════════════════════════════════════════════════════════════════════

  Agent = 模型            ← 一切需要判断的事
  Harness = Tools + Knowledge + Observation + Action Interfaces + Permissions
  Base / 网盘 / 小红书    ← **世界**(状态·唯一真源),不属于 harness

  ── 逐层对位 ─────────────────────────────────────────────────────────────

  ① 【Agent 的地盘】判断有没有跑回代码里?
     orchestrator/ 本该**只有** Tools / Observation / Permissions / Knowledge。
     这一轮我加的东西里,有没有新的 if / 阈值 / 权重 / 规则 / 开关,
     在替模型决定「今天干什么 / 这是什么 / 够不够 / 行不行 / 要不要」?
     ⚠️ 拆掉一条规则后,本能地想"那得给模型一个规则去决定" = **又把导轨装回去了**

  ② 【Knowledge】技能是"知识"还是被当成了"函数"?
     技能应该是:agent 读 SKILL.md → 进上下文 → **模型自己动手**。
     有没有变成 `result = skill.f(x)` 等返回值?
     **同一个方法有没有两份真源?**(SOP 在 SKILL.md 里,代码里又拼了一遍 prompt)

  ③ 【Tools / Action】手是不是纯的?
     它只该做**一次确定性 IO**(读写 base / 拉网盘 / 调 ARK / 转码)。
     有没有在"手"里夹带了判断?

  ④ 【Observation】眼睛有没有在骗人?
     真渲染 今日卡片 / 补拍单 / 周报,以运营和摄影师的眼睛读:
     算了却没给人看?拦了却没说为什么?没核实就断言?数字对但话不对?

  ⑤ 【Permissions】红线还是红线吗?
     有没有旋钮能把它关掉?守卫在不在**任何 IO 之前**?
     该是红线的东西有没有被降级成技能里的一句话?(模型可以不听)

  ⑥ 【世界】Base / 网盘里有没有出现"不属于世界状态"的东西?
     假数据?占位链接?模拟的已发?mock 的点赞?
     **世界只能装真事。**

  ⑦ 【心跳】cron / 定时是"叫醒 agent",还是"替 agent 排作息表"?
     harness 只给"能设定时器"这只手;**几点醒、醒来干什么,是 agent 的判断**。

  ⑧ 【真源】有没有同一个真相长出了第二份拷贝?
     两份拷贝 = 注定漂移。(手抄的技能目录 / 抄第二遍的方法 / 两处写同一个事实)

════════════════════════════════════════════════════════════════════════════
Q
